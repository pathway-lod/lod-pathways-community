#!/usr/bin/env python3
"""
Create RDF for the four cases from the results of the pilots, and validate it against the shapes.

  python build_rdf.py all                     # all four cases -> rdf/*.ttl, each validated
  python build_rdf.py bgc --include-ec        # also the weak EC-only BGC-pathway links
  python build_rdf.py association --max-cluster-p 1.0

Cases and inputs (the pilots must have been run; their result files are committed):
  bgc          pilots/plantismash_overlap/results/*.csv.gz     -> rdf/bgc.ttl
  association  pilots/meantools_overlap/results/*.csv          -> rdf/association.ttl
  annotation   pilots/metabolomics_overlap/results/*.csv       -> rdf/annotation.ttl
               (+ the Zenodo S6 node tables for scores, downloaded by the pilot)
  plantcyc     data/plantmetwiki_citations.csv (SPARQL snapshot) -> rdf/plantcyc.ttl

The graphs are built with rdflib (never by pasting strings), so the Turtle is always syntactically valid.
Policy choices are explicit options and are documented in README.md; weak support is not hidden:
the shapes flag it as warnings.
"""

import argparse
import importlib.util
import math
import re
import sys
from pathlib import Path

import pandas as pd
from rdflib import RDF, RDFS, Graph, Literal, Namespace, URIRef
from rdflib.namespace import DCTERMS, SKOS, XSD

HERE = Path(__file__).parent
PILOTS = HERE.parent / "pilots"
RDF_DIR = HERE / "rdf"
DATA = HERE / "data"

LODP = Namespace("https://example.org/lod-pathways/pilot/")
OBO = Namespace("http://purl.obolibrary.org/obo/")
SIO = Namespace("http://semanticscience.org/resource/")
PROV = Namespace("http://www.w3.org/ns/prov#")
SWO = Namespace("http://www.ebi.ac.uk/swo/")
EDAM = Namespace("http://edamontology.org/")
WP = Namespace("http://vocabularies.wikipathways.org/wp#")
PMW = Namespace("http://rdf-plantmetwiki.bioinformatics.nl/pathways/")
MIBIG = Namespace("https://mibig.secondarymetabolites.org/repository/")
TAIR = Namespace("https://identifiers.org/tair.name/")
PUBMED = Namespace("https://identifiers.org/pubmed/")
INCHIKEY = Namespace("https://identifiers.org/inchikey/")
HAS_EVIDENCE = SIO.SIO_000772

PLANTISMASH_URL = "https://plantismash.bioinformatics.nl/precalc/v2/"
TAIR_LOCUS = re.compile(r"^AT[1-5CM]G\d{5}$")
SOLYC = re.compile(r"(Solyc\d{2}g\d{6})")

# Weakest to strongest is NOT the order here; this is the strength rank, 1 = strongest
TIER_RANK = {"curated": 1, "gene_direct": 2, "gene_locus": 3, "structure_match": 4,
             "gene_uniprot": 5, "gene_ec": 6, "mass_match": 7}


# ----------------------------
# Helpers
# ----------------------------
def new_graph():
    g = Graph()
    for prefix, ns in (("lodp", LODP), ("obo", OBO), ("sio", SIO), ("prov", PROV), ("swo", SWO), ("edam", EDAM),
                       ("wp", WP), ("pmw", PMW), ("mibig", MIBIG), ("tair", TAIR), ("pubmed", PUBMED),
                       ("skos", SKOS), ("dcterms", DCTERMS)):
        g.bind(prefix, ns)
    return g


def slug(text):
    return re.sub(r"[^A-Za-z0-9_]", "_", str(text))


def dbl(x):
    return Literal(float(x), datatype=XSD.double)


def integer(x):
    return Literal(int(x), datatype=XSD.integer)


def add_run(g, name, cls, label, software, version, used, extra=None):
    run = LODP[name]
    g.add((run, RDF.type, cls))
    g.add((run, RDFS.label, Literal(label)))
    g.add((run, LODP.software, Literal(software)))
    if version:
        g.add((run, SWO.SWO_0004000, Literal(version)))
    for u in used:
        g.add((run, PROV.used, URIRef(u)))
    for p, o in (extra or {}).items():
        for v in (o if isinstance(o, list) else [o]):
            g.add((run, p, v))
    return run


def add_evidence(g, claim, run, eco_classes, props=None):
    """A blank evidence node, typed with ECO classes, generated by `run`."""
    from rdflib import BNode
    ev = BNode()
    for c in eco_classes:
        g.add((ev, RDF.type, c))
    g.add((ev, PROV.wasGeneratedBy, run))
    for p, o in (props or {}).items():
        for v in (o if isinstance(o, list) else [o]):
            g.add((ev, p, v))
    g.add((claim, HAS_EVIDENCE, ev))
    return ev


def pathway_iri(pc):
    return PMW[pc]


def load_pilot(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def weakest(tiers):
    return max(tiers, key=TIER_RANK.__getitem__)


def strongest(tiers):
    return min(tiers, key=TIER_RANK.__getitem__)


