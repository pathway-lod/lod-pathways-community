# CLI
# ----------------------------
BUILDERS = {"bgc": build_bgc, "association": build_association, "annotation": build_annotation, "plantcyc": build_plantcyc}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("case", choices=[*BUILDERS, "all"])
    ap.add_argument("--include-ec", action="store_true", help="bgc: also export the weak EC-only links")
    ap.add_argument("--max-cluster-p", type=float, default=0.05, help="association: keep clusters with p below this")
    ap.add_argument("--no-validate", action="store_true")
    ap.add_argument("--out", default=str(RDF_DIR), help="output directory (default: rdf/)")
    args = ap.parse_args(argv)

    import validate
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    failed = False
    for case in (BUILDERS if args.case == "all" else [args.case]):
        kwargs = {"bgc": {"include_ec": args.include_ec}, "association": {"max_cluster_p": args.max_cluster_p}}.get(case, {})
        g, stats = BUILDERS[case](**kwargs)
        out = out_dir / f"{case}.ttl"
        g.serialize(destination=str(out), format="turtle")
        shown = out.relative_to(HERE) if out.is_relative_to(HERE) else out
        print(f"\n== {case}: {len(g)} triples -> {shown} ({out.stat().st_size / 1e6:.1f} MB)")
        for k, v in stats.items():
            print(f"   {k}: {v}")
        if not args.no_validate:
            res = validate.validate(g)
            print("   validation:", f"{res['violations']} violations, {res['warnings']} warnings")
            if res["results"]:
                print("\n".join("   " + line for line in validate.format_report(res, max_examples=2).splitlines()[2:]))
            failed |= res["violations"] > 0
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
