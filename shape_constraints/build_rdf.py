# Case 2: MEANtools gene-metabolite associations
# ----------------------------
def build_association(max_cluster_p=0.05):
    pairs = pd.read_csv(PILOTS / "meantools_overlap/results/cluster_pairs.csv")
    gmap = pd.read_csv(PILOTS / "meantools_overlap/results/gene_pathway_map.csv")
    mmap = pd.read_csv(PILOTS / "meantools_overlap/results/metabolite_pathway_map.csv")
    pcs = pd.read_csv(PILOTS / "meantools_overlap/data/plantmetwiki_pc_pathways.csv")
    pc_of = dict(zip(pcs.plantcyc_id, pcs.pc))

    n_all = len(pairs)
    pairs = pairs[pairs.cluster_P < max_cluster_p]
    n_sig = len(pairs)
    has_stats = pairs[["correlation", "P", "MR", "weight"]].notna().all(axis=1)
    pairs, n_no_stats = pairs[has_stats], int((~has_stats).sum())

    # gene side: the strongest tier available for the gene, with its pathways
    gene_anchor = {}
    for locus, grp in gmap.groupby("locus"):
        tier = strongest(set(grp.tier))
        gene_anchor[locus] = (tier, {pc_of[p] for p in grp[grp.tier == tier].plantcyc_id if str(pc_of.get(p, "")).startswith("PC")})
    met_anchor = {f: {pc_of[p] for p in grp.plantcyc_id if str(pc_of.get(p, "")).startswith("PC")}
                  for f, grp in mmap.groupby("feature")}

    g = new_graph()
    run = add_run(g, "run_meantools_fungal_DR10", LODP.MEANtoolsRun,
                  "MEANtools functional clustering, tomato, fungal treatment, decay rate 10",
                  "MEANtools", "1.0.0", ["https://zenodo.org/records/15697913"], {LODP.decayRate: integer(10)})
    g.add((run, RDF.type, EDAM.operation_3463))
    g.add((run, RDF.type, EDAM.operation_3432))

    n_claims = n_unanchored = 0
    sides = {"gene": 0, "metabolite": 0, "both": 0}
    for _, r in pairs.iterrows():
        gene_tier, gene_pcs = gene_anchor.get(r.locus, (None, set()))
        met_pcs = met_anchor.get(r.metabolite, set())
        shared = {pc_of[p] for p in str(r.shared_pathways).split(", ")} & gene_pcs & met_pcs if pd.notna(r.shared_pathways) else set()
        if shared:
            side, anchors = "both", shared
        elif gene_pcs and met_pcs:
            side, anchors = "both", gene_pcs | met_pcs
        elif gene_pcs:
            side, anchors = "gene", gene_pcs
        elif met_pcs:
            side, anchors = "metabolite", met_pcs
        else:
            n_unanchored += 1
            continue
        tiers = ([gene_tier] if side in ("gene", "both") else []) + (["mass_match"] if side in ("metabolite", "both") else [])

        feature = LODP[f"feature_MTBLS1039_{r.metabolite}"]
        assoc = LODP[f"assoc_fungal_DR10_C{r.Cluster}_{r.locus}_{r.metabolite}"]
        g.add((feature, RDF.type, LODP.MetaboliteFeature))
        g.add((feature, LODP.featureId, Literal(r.metabolite)))
        g.add((feature, LODP.dataset, URIRef("https://www.ebi.ac.uk/metabolights/MTBLS1039")))
        g.add((feature, OBO.MS_1000465, OBO.MS_1000130))   # scan polarity: positive scan
        g.add((assoc, RDF.type, LODP.GeneMetaboliteAssociation))
        g.add((assoc, SIO.SIO_000628, URIRef(f"https://plants.ensembl.org/Solanum_lycopersicum/Gene/Summary?g={r.locus}")))
        g.add((assoc, SIO.SIO_000628, feature))
        for pc in sorted(anchors):
            g.add((assoc, LODP.anchoredInPathway, pathway_iri(pc)))
        g.add((assoc, LODP.anchoredSide, Literal(side)))
        if side in ("gene", "both"):
            g.add((assoc, LODP.geneAnchorTier, Literal(gene_tier)))
        if side in ("metabolite", "both"):
            g.add((assoc, LODP.metaboliteAnchorTier, Literal("mass_match")))
        g.add((assoc, LODP.anchorTier, Literal(weakest(tiers))))
        add_evidence(g, assoc, run, [OBO.ECO_0007590], {
            OBO.STATO_0000280: dbl(r.correlation), OBO.OBI_0000175: dbl(r.P),
            LODP.mutualRank: dbl(r.MR), LODP.edgeWeight: dbl(r.weight),
            LODP.functionalCluster: Literal(str(int(r.Cluster))), LODP.clusterPValue: dbl(r.cluster_P)})
        n_claims += 1
        sides[side] += 1
    return g, {"pairs in all clusters": n_all, f"pairs in clusters with p < {max_cluster_p}": n_sig,
               "skipped: no direct correlation or mutual rank (cluster co-members only)": n_no_stats,
               "skipped: neither side found in PlantMetWiki": n_unanchored,
               "claims": n_claims, "by anchored side": sides}


