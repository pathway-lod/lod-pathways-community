# Case 1: plantiSMASH BGCs and their links to PlantMetWiki pathways
# ----------------------------
def build_bgc(include_ec=False):
    clusters = pd.read_csv(PILOTS / "plantismash_overlap/results/plantismash_clusters.csv.gz")
    links = pd.read_csv(PILOTS / "plantismash_overlap/results/bgc_pathway_links.csv.gz")
    pcs = pd.read_csv(PILOTS / "meantools_overlap/data/plantmetwiki_pc_pathways.csv")
    links = links.merge(pcs[["plantcyc_id", "pc"]].drop_duplicates("plantcyc_id"), on="plantcyc_id", how="left")
    skipped = {"EC-only links not exported (use --include-ec)": 0, "pathway is not a PC pathway": 0}
    if not include_ec:
        skipped["EC-only links not exported (use --include-ec)"] = int((links.best_tier == "gene_ec").sum())
        links = links[links.best_tier != "gene_ec"]
    bad = ~links.pc.fillna("").str.match(r"^PC\d+$")
    skipped["pathway is not a PC pathway"] = int(bad.sum())
    links = links[~bad]

    # genes of the BGCs (optional: only for TAIR loci), from the pilot's cache of the plantiSMASH database
    genes = None
    try:
        ps = load_pilot(PILOTS / "plantismash_overlap/match_plantismash.py", "match_plantismash")
        _, genes = ps.load_plantismash()
        genes = genes[genes.biosynthetic & genes.locus_tag.fillna("").str.match(TAIR_LOCUS.pattern)]
    except Exception as e:  # cache not available: has-part is optional in the shapes
        print(f"note: BGC gene lists not available ({type(e).__name__}); skipping obo:BFO_0000051", file=sys.stderr)

    g = new_graph()
    plantismash = add_run(g, "run_plantismash", LODP.PlantiSMASHRun, "plantiSMASH precalculated database",
                          "plantiSMASH", "2.0 (precalculated database v2)", [PLANTISMASH_URL])
    linking = add_run(g, "run_bgc_pathway_linking", LODP.LinkingRun,
                      "Linking of plantiSMASH BGCs to PlantMetWiki pathways",
                      "lod-pathways pilots/plantismash_overlap", "pilot snapshot 2026-09-29",
                      [PLANTISMASH_URL, "https://plantmetwiki.bioinformatics.nl/sparql", "https://rest.uniprot.org/"])

    for _, c in clusters[clusters.bgc.isin(links.bgc)].iterrows():
        bgc = URIRef(PLANTISMASH_URL + c.bgc.replace("/#", "/index.html#"))
        g.add((bgc, RDF.type, OBO.SO_0002357))
        g.add((bgc, RDFS.label, Literal(c.bgc)))
        g.add((bgc, WP.organismName, Literal(c.species)))
        if pd.notna(c.assembly):
            g.add((bgc, LODP.genomeAssembly, Literal(c.assembly)))
        if genes is not None:
            for locus in genes.loc[genes.bgc == c.bgc, "locus_tag"].unique():
                g.add((bgc, OBO.BFO_0000051, TAIR[locus]))
        props = {LODP.detectionRule: [Literal(r) for r in c["type"].split("-")]}
        if pd.notna(c.core_domains) and c.core_domains:
            props[LODP.coreDomain] = [Literal(d) for d in c.core_domains.split(", ")]
        add_evidence(g, bgc, plantismash, [OBO.ECO_0000256, OBO.ECO_0007327], props)
        if pd.notna(c.mibig_id) and pd.notna(c.mibig_similarity):
            g.add((bgc, SKOS.exactMatch if c.mibig_similarity == 100 else SKOS.closeMatch, MIBIG[c.mibig_id]))
            from rdflib import BNode
            ev = BNode()
            g.add((ev, RDF.type, OBO.ECO_0000249))
            g.add((ev, PROV.wasGeneratedBy, plantismash))
            g.add((ev, LODP.percentGenesSimilar, integer(c.mibig_similarity)))
            g.add((bgc, LODP.mibigMatchEvidence, ev))

    for _, r in links.iterrows():
        bgc = URIRef(PLANTISMASH_URL + r.bgc.replace("/#", "/index.html#"))
        link = LODP[f"link_{slug(r.bgc)}_{r.pc}"]
        g.add((link, RDF.type, LODP.BGCPathwayLink))
        g.add((link, OBO.RO_0002131, bgc))
        g.add((link, OBO.RO_0002131, pathway_iri(r.pc)))
        g.add((link, LODP.anchoredInPathway, pathway_iri(r.pc)))
        g.add((link, LODP.anchorTier, Literal(r.best_tier)))
        props = {LODP.linkTier: Literal(r.best_tier), LODP.nSharedGenes: integer(r.n_bgc_genes)}
        for node in sorted(set(r.linking_nodes.split(", "))):
            key = (LODP.linkingEC, node[3:]) if node.startswith("EC ") else \
                  (LODP.linkingGene, node) if TAIR_LOCUS.match(node) else (LODP.linkingProtein, node)
            props.setdefault(key[0], []).append(Literal(key[1]))
        if r.n_direct_genes and r.pathway_n_tair_genes:
            props[LODP.nPathwayGenes] = integer(r.pathway_n_tair_genes)
            props[LODP.fractionPathwayGenes] = dbl(r.n_direct_genes / r.pathway_n_tair_genes)
        if r.n_ecs and pd.notna(r.ec_overlap):
            props[LODP.nSharedEC] = integer(r.n_ecs)
            props[LODP.fractionPathwayECs] = dbl(r.ec_overlap)
        add_evidence(g, link, linking, [OBO.ECO_0007679], props)
    return g, {"BGCs": clusters.bgc.isin(links.bgc).sum(), "links": len(links), **skipped}


