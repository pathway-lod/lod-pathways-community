def eco_for_plantcyc(code):
    """Proposed mapping of PlantCyc evidence codes to ECO (by meaning, not an official crosswalk)."""
    if code.startswith("EV-EXP-IDA"):
        return OBO.ECO_0000314
    return {"EV-EXP-IEP": OBO.ECO_0000270, "EV-EXP-TAS": OBO.ECO_0000304, "EV-AS-TAS": OBO.ECO_0000304,
            "EV-EXP": OBO.ECO_0000006, "EV-COMP-HINF-SEQ-ORTHOLOGY": OBO.ECO_0000266, "EV-IC": OBO.ECO_0000305}.get(code)


def parse_citations(value):
    """'7979352:EV-EXP-IDA:3563:name, 7979352:EV-EXP-IDA-PURIFIED-PROTEIN' -> [(ref, code), ...] (names are dropped)."""
    out = []
    for entry in str(value).split(", "):
        m = re.match(r"^([^:]*):(EV-[A-Z0-9-]+)", entry.strip())
        if m:
            out.append((m.group(1), m.group(2)))
    return list(dict.fromkeys(out))


def build_plantcyc():
    path = DATA / "plantmetwiki_citations.csv"
    if not path.exists():
        import requests
        q = ('PREFIX v: <http://rdf-plantmetwiki.bioinformatics.nl/vocab/> SELECT DISTINCT ?node ?val WHERE '
             '{ ?node v:gpmlProperty ?b . ?b v:key "^citations" ; v:value ?val . }')
        r = requests.get("https://plantmetwiki.bioinformatics.nl/sparql", params={"query": q},
                         headers={"Accept": "text/csv"}, timeout=300)
        r.raise_for_status()
        path.write_text(r.text)
    cit = pd.read_csv(path)
    g = new_graph()
    run = add_run(g, "run_plantcyc", LODP.PlantCycCuration, "PlantCyc curation, as released in PlantMetWiki",
                  "PlantCyc", "17.0.0", ["https://pmn.plantcyc.org/"])
    n_claims = n_entries = n_no_code = n_unmapped = n_bad_node = 0
    for _, r in cit.iterrows():
        entries = parse_citations(r.val)
        if not entries:
            n_no_code += 1
            continue
        m = re.match(r"^http://rdf-plantmetwiki\.bioinformatics\.nl/Pathway/(PC\d+)_[^/]+/(DataNode|Interaction)/.+$", r.node)
        if not m:   # nodes of single-reaction diagrams (RC...) are not PlantCyc pathways
            n_bad_node += 1
            continue
        pc = m.group(1)
        mapped = [(ref, code, eco_for_plantcyc(code)) for ref, code in entries]
        n_unmapped += sum(e is None for _, _, e in mapped)
        mapped = [e for e in mapped if e[2] is not None]
        if not mapped:
            continue
        claim = LODP[f"claim_{slug(r.node.split('/Pathway/')[1])}"]
        g.add((claim, RDF.type, LODP.PathwayMembershipClaim))
        g.add((claim, RDF.subject, URIRef(r.node)))
        g.add((claim, RDF.predicate, DCTERMS.isPartOf))
        g.add((claim, RDF.object, pathway_iri(pc)))
        g.add((claim, LODP.anchoredInPathway, pathway_iri(pc)))
        g.add((claim, LODP.anchorTier, Literal("curated")))
        for ref, code, eco in mapped:
            props = {LODP.originalEvidenceCode: Literal(code)}
            if re.fullmatch(r"\d+", ref):
                props[DCTERMS.references] = PUBMED[ref]
            add_evidence(g, claim, run, [eco], props)
            n_entries += 1
        n_claims += 1
    return g, {"claims (nodes)": n_claims, "evidence entries": n_entries,
               "values without an EV- code (plain PubMed lists)": n_no_code, "codes without ECO mapping": n_unmapped,
               "nodes in single-reaction diagrams (RC), not PC pathways": n_bad_node}


