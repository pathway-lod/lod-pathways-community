TOOLS = {  # tier: (run name, label, software, version)
    "gnps_library": ("run_gnps_library", "GNPS spectral library search", "GNPS library search", None),
    "sirius": ("run_sirius", "SIRIUS on the Brassicaceae LC-MS/MS data", "SIRIUS", "6.1.0"),
    "ms2query_exact": ("run_ms2query", "MS2Query on the Brassicaceae LC-MS/MS data", "MS2Query", "1.0"),
    "dreams": ("run_dreams", "DreaMS on the Brassicaceae LC-MS/MS data", "DreaMS", "1.0"),
}
TOOL_NAMES = {"sirius": "SIRIUS", "ms2query": "MS2Query", "dreams": "DreaMS"}
DATASET_14270 = "https://www.ebi.ac.uk/metabolights/MTBLS14270"


def _num(row, col):
    """A finite number from the node table, or None. SIRIUS reports -Infinity when it computed no confidence."""
    v = row.get(col)
    try:
        x = float(v) if v is not None and str(v) not in ("", "nan", "none") else None
    except ValueError:
        return None
    return x if x is not None and math.isfinite(x) else None


def build_annotation():
    hits = pd.read_csv(PILOTS / "metabolomics_overlap/results/feature_hits.csv")
    hits = hits[hits.tier != "ms2query_analog"]            # analogues are related compounds, not detections
    pm = load_pilot(PILOTS / "metabolomics_overlap/match_plantmetwiki.py", "match_plantmetwiki")
    nodes = {mode: df.set_index("shared name") for mode, df in pm.load_nodetables().items()}

    g = new_graph()
    runs = {tier: add_run(g, name, LODP.AnnotationToolRun, label, software, version, [DATASET_14270])
            for tier, (name, label, software, version) in TOOLS.items()}
    consensus = add_run(g, "run_consensus", LODP.ConsensusAnnotationRun, "Consensus annotation of SIRIUS, MS2Query and DreaMS",
                        "Consensus_annotator (Annotation_matching_module_update_report_v02.py)",
                        "git 59d225b of capsicumbaccatum/Metabolic_fingerprinting_consensus_annotation",
                        ["https://doi.org/10.5281/zenodo.19391098"],
                        {LODP.usesTool: [Literal("SIRIUS 6.1.0"), Literal("MS2Query 1.0"), Literal("DreaMS 1.0")]})

    n_claims = n_evidence = 0
    for (mode, fid, key14), grp in hits.groupby(["mode", "feature_id", "key14"]):
        row = nodes[mode].loc[str(fid)]
        polarity = OBO.MS_1000130 if mode == "pos" else OBO.MS_1000129   # positive scan / negative scan
        feature = LODP[f"feature_MTBLS14270_{mode}_{fid}"]
        g.add((feature, RDF.type, LODP.MetaboliteFeature))
        g.add((feature, LODP.featureId, Literal(str(fid))))
        g.add((feature, LODP.dataset, URIRef(DATASET_14270)))
        g.add((feature, OBO.MS_1000465, polarity))   # scan polarity

        keys = sorted(set(str(grp.pmw_inchikeys.iloc[0]).split(" | ")))
        claim = LODP[f"annotation_MTBLS14270_{mode}_{fid}_{key14}"]
        g.add((claim, RDF.type, LODP.MetaboliteAnnotation))
        g.add((claim, LODP.feature, feature))
        for k in keys:
            g.add((claim, SKOS.closeMatch, INCHIKEY[k]))
            g.add((claim, LODP.anchoredToMetabolite, INCHIKEY[k]))
        if isinstance(grp.wikidata.iloc[0], str):
            for q in sorted(set(grp.wikidata.iloc[0].split(" | "))):
                g.add((claim, SKOS.closeMatch, URIRef(q)))
        g.add((claim, LODP.anchorTier, Literal("structure_match")))
        g.add((claim, LODP.matchLevel, Literal("connectivity")))

        for tier in grp.tier:
            if tier == "consensus_inchi":
                cols = str(row.get("match_columns_inchi", ""))
                agreeing = sorted({TOOL_NAMES[c.strip().split("_")[0]] for c in cols.split(",") if c.strip().split("_")[0] in TOOL_NAMES})
                mtype = str(row.get("match_type_inchi"))
                props = {LODP.identificationTier: Literal(tier), LODP.matchType: Literal(mtype),
                         LODP.agreementScore: dbl(1.0 if mtype == "full" else 0.5),
                         LODP.agreeingTool: [Literal(t) for t in agreeing]}
                add_evidence(g, claim, consensus, [OBO.ECO_0007653, OBO.ECO_0001580], props)
            else:
                props = {LODP.identificationTier: Literal(tier)}
                if tier == "sirius" and _num(row, "sirius_ConfidenceScoreApproximate") is not None:
                    props[LODP.siriusConfidenceApprox] = dbl(_num(row, "sirius_ConfidenceScoreApproximate"))
                if tier == "ms2query_exact":
                    if _num(row, "ms2query_ms2query_model_prediction") is not None:
                        props[LODP.ms2queryModelScore] = dbl(_num(row, "ms2query_ms2query_model_prediction"))
                    if _num(row, "ms2query_precursor_mz_difference") is not None:
                        props[LODP.precursorMzDifference] = dbl(_num(row, "ms2query_precursor_mz_difference"))
                if tier == "dreams" and _num(row, "dreams_DreaMS similarity") is not None:
                    props[LODP.dreamsSimilarity] = dbl(_num(row, "dreams_DreaMS similarity"))
                if tier == "gnps_library" and isinstance(row.get("library_compound_name"), str):
                    props[LODP.libraryCompoundName] = Literal(row["library_compound_name"])
                eco = [OBO.ECO_0001580] if tier == "gnps_library" else [OBO.ECO_0007669, OBO.ECO_0001580]
                add_evidence(g, claim, runs[tier], eco, props)
            n_evidence += 1
        n_claims += 1
    return g, {"claims (feature x metabolite)": n_claims, "evidence nodes (tiers)": n_evidence}


